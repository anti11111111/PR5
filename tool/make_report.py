def set_run_font(run, size):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.bold = False
    run.font.color.rgb = RGBColor(0, 0, 0)
    r_pr = run._element.get_or_add_rPr()
    fonts = r_pr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        r_pr.append(fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(attr), "Times New Roman")


def add_body(doc, text):
    paragraph = doc.add_paragraph()
    fmt = paragraph.paragraph_format
    fmt.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    fmt.line_spacing = 1.5
    fmt.space_before = Pt(0)
    fmt.space_after = Pt(0)
    fmt.first_line_indent = Cm(1.25)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    set_run_font(paragraph.add_run(text), 14)


def add_caption(doc, text):
    paragraph = doc.add_paragraph()
    fmt = paragraph.paragraph_format
    fmt.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    fmt.line_spacing = 1.5
    fmt.space_before = Pt(6)
    fmt.space_after = Pt(6)
    fmt.first_line_indent = Cm(0)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_run_font(paragraph.add_run(text), 12)


def add_picture(doc, path):
    with Image.open(path) as image:
        width_px, height_px = image.size
    max_w = 15.5
    max_h = 16.0
    width = max_w
    height = width * height_px / width_px
    if height > max_h:
        height = max_h
        width = height * width_px / height_px
    paragraph = doc.add_paragraph()
    fmt = paragraph.paragraph_format
    fmt.line_spacing = 1.0
    fmt.space_before = Pt(12)
    fmt.space_after = Pt(0)
    fmt.first_line_indent = Cm(0)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.add_run().add_picture(str(path), width=Cm(width))


def build():
    doc = Document()
    section = doc.sections[0]
    section.page_width = Mm(210)
    section.page_height = Mm(297)
    section.left_margin = Mm(30)
    section.right_margin = Mm(15)
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)

    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(14)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.first_line_indent = Cm(1.25)
    r_pr = normal.element.get_or_add_rPr()
    fonts = r_pr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        r_pr.append(fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(attr), "Times New Roman")

    add_body(
        doc,
        "Цель работы — добавить к каталогу автосалона регистрацию, вход и три роли с разными экранами. "
        "Читатель смотрит каталог и свои брони, менеджер ведёт клиентов и стойку, администратор управляет пользователями и статистикой. "
        "Закрытый адрес не открывается вручную, пароль проверяется при наборе, сессия заканчивается после простоя, а отказ сервера не зависит от роли, записанной в браузере.",
    )

    for index, (filename, caption, text) in enumerate(FIGURES, start=1):
        add_picture(doc, SHOTS / filename)
        add_caption(doc, f"Рисунок {index} — {caption}")
        add_body(doc, text)

    add_body(
        doc,
        "Вывод. Вход показывает имя и роль, неверный пароль оставляет человека на форме с текстом «Неверная почта или пароль.», "
        "а при регистрации правила пароля видны сразу: на снимке длина уже достаточная, цифры и специального символа нет. "
        "У Анны Павловой на главной есть «Мои брони», у менеджера зала — «Клиенты» и «Стойка менеджера», "
        "у Мирзаханян Амазасп — «Пользователи» и «Статистика». Адрес /users у читателя открывает экран «Недостаточно прав». "
        "Карточка предупреждает, что сессия закроется через 30 секунд, а после выхода форма входа пишет «Сессия завершена из-за неактивности.» "
        "Подмена роли в браузере рисует Анне Павловой кнопки администратора, но список пользователей сервер не отдаёт и отвечает «Недостаточно прав для этого действия.»",
    )

    doc.save(OUT)
    print(OUT)


if __name__ == "__main__":
    build()
